/**
 * The app's icon set: small stroke SVGs in a shared 24×24 grid, drawn with
 * `currentColor` so each button controls its own tint and size.
 *
 * Inline SVG beats both alternatives here. Emoji render differently on every
 * platform and read as foreign objects next to text (they were what made the
 * account buttons feel clunky), and an icon font would add a dependency and a
 * load step for fifteen shapes. These are just components.
 */
function Svg({ size = 24, children, ...rest }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...rest}
    >
      {children}
    </svg>
  );
}

